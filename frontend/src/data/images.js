export function img(id) {
    if (!id) return "/images/photo-1610992015836-7c249d75782d.jpg";
    if (id.startsWith("/")) return id;
    if (id.startsWith("http://") || id.startsWith("https://")) {
        const m = id.match(/photo-([a-zA-Z0-9_-]+)/);
        if (m) return `/images/photo-${m[1]}.jpg`;
        return id;
    }
    return `/images/photo-${id}.jpg`;
}

